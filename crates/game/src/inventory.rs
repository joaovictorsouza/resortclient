pub const ALL_CATEGORIES: &str = "all";

/// Asset path of the thumbnail generated by `resort-game-assets` (`tools/asset_pipeline/render_item_thumbnails.py`).
pub fn thumbnail_path(catalog_id: &str) -> String {
    format!("ui/thumbs/{catalog_id}.png")
}

pub fn category_label(category: &str) -> &str {
    match category {
        ALL_CATEGORIES => "Todos",
        "collider" => "Móveis",
        "floor_decoration" => "Pisos",
        other => other,
    }
}

pub fn category_icon(category: &str) -> &'static str {
    match category {
        "collider" => "ui/icons/armchair.png",
        "floor_decoration" => "ui/icons/rug.png",
        _ => "ui/icons/package.png",
    }
}

pub fn type_label(item: &InventoryItemDto) -> &'static str {
    if item.walkable {
        "Piso decorativo"
    } else {
        "Móvel sólido"
    }
}

/// Category keys present in the inventory (in first-seen order), preceded by "all".
pub fn available_categories(items: &[InventoryItemDto]) -> Vec<String> {
    let mut keys = vec![ALL_CATEGORIES.to_string()];
    for item in items {
        if !keys.contains(&item.category) {
            keys.push(item.category.clone());
        }
    }
    keys
}

/// Lowercases and strips common Portuguese diacritics so "poltrona" matches "Poltrona" and
/// "divisoria" matches "Divisória".
pub fn normalize_search(text: &str) -> String {
    text.chars()
        .flat_map(char::to_lowercase)
        .map(|c| match c {
            'á' | 'à' | 'â' | 'ã' | 'ä' => 'a',
            'é' | 'è' | 'ê' | 'ë' => 'e',
            'í' | 'ì' | 'î' | 'ï' => 'i',
            'ó' | 'ò' | 'ô' | 'õ' | 'ö' => 'o',
            'ú' | 'ù' | 'û' | 'ü' => 'u',
            'ç' => 'c',
            other => other,
        })
        .collect()
}

/// Items matching the selected category (`None` or "all" keeps everything) whose name contains
/// the search text (case and accent insensitive; blank keeps everything).
pub fn filter_items<'a>(
    items: &'a [InventoryItemDto],
    category: Option<&str>,
    query: &str,
) -> Vec<&'a InventoryItemDto> {
    let query = normalize_search(query.trim());
    items
        .iter()
        .filter(|item| match category {
            None | Some(ALL_CATEGORIES) => true,
            Some(cat) => item.category == cat,
        })
        .filter(|item| query.is_empty() || normalize_search(&item.name).contains(&query))
        .collect()
}

/// The selected item if it is still visible, otherwise the first visible one.
pub fn resolve_selection<'a>(
    visible: &[&'a InventoryItemDto],
    selected: Option<&str>,
) -> Option<&'a InventoryItemDto> {
    selected
        .and_then(|id| visible.iter().copied().find(|item| item.catalog_id == id))
        .or_else(|| visible.first().copied())
}

/// Scrollbar thumb geometry for a scrollable area.
///
/// `visible` and `content` are the viewport and content heights, `offset` the scroll offset (same
/// unit). Returns `None` when everything fits, otherwise `(ratio, progress)`: the thumb's share of
/// the track (clamped to a minimum so it stays grabbable) and how far along the track it sits (0..=1).
pub fn scrollbar_metrics(visible: f32, content: f32, offset: f32) -> Option<(f32, f32)> {
    const MIN_RATIO: f32 = 0.1;
    if visible <= 0.0 || content <= visible + 0.5 {
        return None;
    }
    let ratio = (visible / content).clamp(MIN_RATIO, 1.0);
    let progress = (offset / (content - visible)).clamp(0.0, 1.0);
    Some((ratio, progress))
}

