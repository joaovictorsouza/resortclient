#[derive(Resource, Default, Debug)]
pub struct InventoryFilter {
    pub category: Option<String>,
    pub query: String,
}

#[derive(Component)]
struct InventoryUiRoot;

/// Inventory systems only run in a room; close the window when leaving it so no dead overlay stays.
fn close_inventory_on_leaving_room(
    mut commands: Commands,
    mut inventory: ResMut<PlayerInventoryState>,
    roots: Query<Entity, With<InventoryUiRoot>>,
) {
    inventory.is_open = false;
    for root in &roots {
        commands.entity(root).despawn();
    }
}

#[derive(Resource)]
struct InventoryTemplates {
    window: Handle<HtmlTemplate>,
    slot: Handle<HtmlTemplate>,
    category: Handle<HtmlTemplate>,
    detail: Handle<HtmlTemplate>,
}

