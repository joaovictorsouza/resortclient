pub struct InventoryPlugin;

impl Plugin for InventoryPlugin {
    fn build(&self, app: &mut App) {
        crate::ensure_hui_plugins(app);
        app.init_resource::<InventoryFilter>()
            .add_systems(Startup, setup_inventory_ui)
            .add_systems(OnExit(AppState::InRoom), close_inventory_on_leaving_room)
            .add_systems(
                Update,
                (
                    toggle_inventory_from_hud,
                    close_inventory_on_escape,
                    sync_search_placeholder,
                    sync_inventory_window,
                    scroll_inventory_grid,
                    update_inventory_scrollbar,
                )
                    .chain()
                    .run_if(in_state(AppState::InRoom)),
            );
    }
}

fn setup_inventory_ui(
    mut commands: Commands,
    server: Res<AssetServer>,
    mut functions: HtmlFunctions,
) {
    commands.insert_resource(InventoryTemplates {
        window: server.load("ui/inventory.html"),
        slot: server.load("ui/inventory_slot.html"),
        category: server.load("ui/inventory_category.html"),
        detail: server.load("ui/inventory_detail.html"),
    });

    functions.register(
        "inv_close",
        |_: In<Entity>, mut state: ResMut<PlayerInventoryState>| {
            state.is_open = false;
        },
    );
    functions.register(
        "inv_select",
        |In(entity): In<Entity>, tags: Query<&Tags>, mut state: ResMut<PlayerInventoryState>| {
            if let Some(id) = tags.get(entity).ok().and_then(|t| t.get("catalog_id")) {
                state.selected_catalog_id = Some(id.clone());
            }
        },
    );
    functions.register(
        "inv_filter",
        |In(entity): In<Entity>, tags: Query<&Tags>, mut filter: ResMut<InventoryFilter>| {
            if let Some(key) = tags.get(entity).ok().and_then(|t| t.get("key")) {
                filter.category = (key != ALL_CATEGORIES).then(|| key.clone());
            }
        },
    );
    functions.register(
        "inv_search_changed",
        |In(entity): In<Entity>, inputs: Query<&TextInput>, mut filter: ResMut<InventoryFilter>| {
            if let Ok(input) = inputs.get(entity)
                && filter.query != input.value
            {
                filter.query = input.value.clone();
            }
        },
    );
    functions.register("inv_place", place_selected_item);
}

fn place_selected_item(
    In(entity): In<Entity>,
    tags: Query<&Tags>,
    mut inventory: ResMut<PlayerInventoryState>,
    mut build_state: ResMut<BuildModeState>,
    room_meta: Option<Res<ActiveRoomMetadata>>,
) {
    if !room_meta.is_some_and(|m| m.is_owner) {
        return;
    }
    let Some(catalog_id) = tags.get(entity).ok().and_then(|t| t.get("catalog_id")) else {
        return;
    };
    let Some(item) = inventory.items.iter().find(|i| &i.catalog_id == catalog_id) else {
        return;
    };
    info!("Entering build mode with item: {}", item.name);
    build_state.is_active = true;
    build_state.skip_first_click = true;
    build_state.active_tool = BuildTool::Placing {
        catalog_id: item.catalog_id.clone(),
        base_width: item.width,
        base_depth: item.depth,
        walkable: item.walkable,
        color: parse_hex_color(&item.color),
        rotation: 0,
    };
    inventory.is_open = false; // Close the window to begin placing.
}

