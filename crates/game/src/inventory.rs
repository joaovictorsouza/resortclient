fn toggle_inventory_from_hud(
    button: Query<&Interaction, (Changed<Interaction>, With<HudInventoryBtn>)>,
    mut inventory: ResMut<PlayerInventoryState>,
    net: Option<Res<NakamaResource>>,
) {
    if !button.iter().any(|i| *i == Interaction::Pressed) {
        return;
    }
    inventory.is_open = !inventory.is_open;
    if inventory.is_open {
        inventory.is_loading = true;
        if let Some(net) = &net {
            net.handle.send_command(NakamaCommand::FetchInventory);
        }
    }
}

/// Esc first leaves the search field (if focused), and only then closes the window.
fn close_inventory_on_escape(
    mut commands: Commands,
    keys: Res<ButtonInput<KeyCode>>,
    mut inventory: ResMut<PlayerInventoryState>,
    focused_inputs: Query<Entity, (With<TextInput>, With<UiActive>)>,
) {
    if !inventory.is_open || !keys.just_pressed(KeyCode::Escape) {
        return;
    }
    if focused_inputs.is_empty() {
        inventory.is_open = false;
    } else {
        for entity in &focused_inputs {
            commands.entity(entity).remove::<UiActive>();
        }
    }
}

/// Shows the "Buscar item..." hint only while the search field is empty.
fn sync_search_placeholder(
    inputs: Query<(&TextInput, &UiId)>,
    mut placeholders: Query<(&UiId, &mut Visibility)>,
) {
    let Some((input, _)) = inputs.iter().find(|(_, id)| id.id() == "inv_search") else {
        return;
    };
    let wanted = if input.value.is_empty() {
        Visibility::Inherited
    } else {
        Visibility::Hidden
    };
    for (id, mut visibility) in &mut placeholders {
        if id.id() == "inv_search_ph" && *visibility != wanted {
            *visibility = wanted;
        }
    }
}

/// Keeps the window entity in sync with `PlayerInventoryState.is_open` and refills the grid,
/// category list and detail panel whenever the inventory, selection or filter changes.
fn sync_inventory_window(
    mut commands: Commands,
    templates: Option<Res<InventoryTemplates>>,
    inventory: Res<PlayerInventoryState>,
    mut filter: ResMut<InventoryFilter>,
    room_meta: Option<Res<ActiveRoomMetadata>>,
    safe_area: Res<SafeArea>,
    ui_scale: Res<UiScale>,
    ui_font: Res<UiFont>,
    roots: Query<Entity, With<InventoryUiRoot>>,
    ids: Query<(Entity, &UiId)>,
    scrolls: Query<(), With<ScrollPosition>>,
    mut needs_fill: Local<bool>,
) {
    let Some(templates) = templates else { return };

    if !inventory.is_open {
        for root in &roots {
            commands.entity(root).despawn();
        }
        *needs_fill = false;
        if filter.category.is_some() || !filter.query.is_empty() {
            *filter = InventoryFilter::default(); // the search field is rebuilt empty next time
        }
        return;
    }

    if safe_area.is_changed() || ui_scale.is_changed() {
        // The spacers that keep the content inside the safe area are fixed when the window is
        // built: rebuild it (e.g. after a rotation).
        for root in &roots {
            commands.entity(root).despawn();
        }
        *needs_fill = true;
        return;
    }
    if roots.is_empty() {
        commands.spawn((
            InventoryUiRoot,
            // A clickable root blocks the HUD buttons below the window (see `LegacyButton`).
            crate::LegacyButton,
            HtmlNode(templates.window.clone()),
            safe_area.modal_properties(ui_scale.0),
            GlobalZIndex(50),
        ));
        *needs_fill = true;
    }
    if inventory.is_changed() || filter.is_changed() {
        *needs_fill = true;
    }
    if !*needs_fill {
        return;
    }

    let find = |name: &str| ids.iter().find(|(_, id)| id.id() == name).map(|(e, _)| e);
    let (Some(grid), Some(cats), Some(detail), Some(scroll)) = (
        find("inv_grid"),
        find("inv_cats"),
        find("inv_detail"),
        find("inv_scroll"),
    ) else {
        return; // template not built yet; retry next frame
    };
    *needs_fill = false;

    let is_owner = room_meta.is_some_and(|m| m.is_owner);
    let visible = filter_items(&inventory.items, filter.category.as_deref(), &filter.query);
    let selected = resolve_selection(&visible, inventory.selected_catalog_id.as_deref());

    // Categories
    commands.entity(cats).despawn_children();
    commands.entity(cats).with_children(|parent| {
        for key in available_categories(&inventory.items) {
            let active = filter.category.as_deref().unwrap_or(ALL_CATEGORIES) == key;
            parent.spawn((
                HtmlNode(templates.category.clone()),
                TemplateProperties::default()
                    .with("key", &key)
                    .with("label", category_label(&key))
                    .with("icon", category_icon(&key))
                    .with(
                        "bg",
                        if active {
                            CATEGORY_BG_SELECTED
                        } else {
                            CATEGORY_BG
                        },
                    ),
            ));
        }
    });

    // Grid
    commands.entity(grid).despawn_children();
    // Keep the scroll offset across refills (e.g. selecting an item); jump to the top only when
    // the visible set changes because of the filter.
    if scrolls.get(scroll).is_err() || filter.is_changed() {
        commands.entity(scroll).insert(ScrollPosition::default());
    }
    commands.entity(grid).with_children(|parent| {
        if visible.is_empty() {
            let message = if inventory.is_loading {
                "Carregando..."
            } else if !filter.query.trim().is_empty() {
                "Nenhum item encontrado."
            } else {
                "Nenhum item aqui."
            };
            parent.spawn((
                Text::new(message),
                ui_font.text_font(14.0),
                TextColor(Color::srgb(0.58, 0.64, 0.72)),
            ));
        }
        for item in &visible {
            let is_selected = selected.is_some_and(|s| s.catalog_id == item.catalog_id);
            parent.spawn((
                HtmlNode(templates.slot.clone()),
                TemplateProperties::default()
                    .with("catalog_id", &item.catalog_id)
                    .with("name", &item.name)
                    .with("thumb", &thumbnail_path(&item.catalog_id))
                    .with("qty", &item.quantity.to_string())
                    .with(
                        "border",
                        if is_selected {
                            SLOT_BORDER_SELECTED
                        } else {
                            SLOT_BORDER
                        },
                    ),
            ));
        }
    });

    // Detail panel
    commands.entity(detail).despawn_children();
    if let Some(item) = selected {
        commands.entity(detail).with_children(|parent| {
            parent.spawn((
                HtmlNode(templates.detail.clone()),
                TemplateProperties::default()
                    .with("catalog_id", &item.catalog_id)
                    .with("name", &item.name)
                    .with("thumb", &thumbnail_path(&item.catalog_id))
                    .with("kind", type_label(item))
                    .with("size", &format!("{}x{}", item.width, item.depth))
                    .with("qty", &item.quantity.to_string())
                    .with("place_display", if is_owner { "flex" } else { "none" })
                    .with("note_display", if is_owner { "none" } else { "flex" }),
            ));
        });
    }
}

fn scroll_inventory_grid(
    mut wheel: MessageReader<MouseWheel>,
    ids: Query<(&UiId, &mut ScrollPosition)>,
) {
    let delta: f32 = wheel
        .read()
        .map(|ev| match ev.unit {
            MouseScrollUnit::Line => ev.y * SCROLL_LINE_PX,
            MouseScrollUnit::Pixel => ev.y,
        })
        .sum();
    if delta == 0.0 {
        return;
    }
    for (id, mut scroll) in ids {
        if id.id() == "inv_scroll" {
            scroll.y = (scroll.y - delta).max(0.0);
        }
    }
}

/// Drives the scrollbar thumb (a full-height child of the track) with `UiTransform`: scaling its
/// height to the visible fraction and translating it to the scroll progress.
fn update_inventory_scrollbar(
    scrolls: Query<(&UiId, &ComputedNode, &ScrollPosition)>,
    mut parts: Query<(&UiId, &mut UiTransform, &mut Visibility)>,
) {
    let Some((_, scroll_node, position)) = scrolls.iter().find(|(id, ..)| id.id() == "inv_scroll")
    else {
        return;
    };
    let metrics = scrollbar_metrics(
        scroll_node.size().y,
        scroll_node.content_size().y,
        position.y / scroll_node.inverse_scale_factor,
    );
    for (id, mut transform, mut visibility) in &mut parts {
        match (id.id().as_str(), metrics) {
            ("inv_track", metrics) => {
                let wanted = if metrics.is_some() {
                    Visibility::Inherited
                } else {
                    Visibility::Hidden
                };
                if *visibility != wanted {
                    *visibility = wanted;
                }
            }
            ("inv_thumb", Some((ratio, progress))) => {
                // The thumb fills the track; scaling happens around its center.
                let center = ratio / 2.0 + progress * (1.0 - ratio);
                transform.scale = Vec2::new(1.0, ratio);
                transform.translation = Val2::percent(0.0, (center - 0.5) * 100.0);
            }
            _ => {}
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn item(id: &str, category: &str) -> InventoryItemDto {
        InventoryItemDto {
            id: format!("inst_{id}"),
            catalog_id: id.to_string(),
            name: id.to_string(),
            category: category.to_string(),
            quantity: 1,
            width: 1,
            depth: 1,
            walkable: category == "floor_decoration",
            color: "#ffffff".to_string(),
            asset_id: String::new(),
        }
    }

    fn sample() -> Vec<InventoryItemDto> {
        vec![
            item("chair", "collider"),
            item("rug", "floor_decoration"),
            item("sofa", "collider"),
        ]
    }

    #[test]
    fn thumbnail_path_uses_catalog_id() {
        assert_eq!(
            thumbnail_path("seat_stool_1x1"),
            "ui/thumbs/seat_stool_1x1.png"
        );
    }

    #[test]
    fn categories_start_with_all_and_are_unique() {
        assert_eq!(
            available_categories(&sample()),
            vec!["all", "collider", "floor_decoration"]
        );
        assert_eq!(available_categories(&[]), vec!["all"]);
    }

    #[test]
    fn filter_by_category() {
        let items = sample();
        assert_eq!(filter_items(&items, None, "").len(), 3);
        assert_eq!(filter_items(&items, Some("all"), "").len(), 3);
        let colliders = filter_items(&items, Some("collider"), "");
        assert_eq!(
            colliders
                .iter()
                .map(|i| i.catalog_id.as_str())
                .collect::<Vec<_>>(),
            vec!["chair", "sofa"]
        );
        assert!(filter_items(&items, Some("unknown"), "").is_empty());
    }

    #[test]
    fn search_is_case_and_accent_insensitive() {
        let mut items = sample();
        items[0].name = "Poltrona de Couro".to_string();
        items[2].name = "Divisória 2x1".to_string();
        let names = |q: &str, cat: Option<&str>| {
            filter_items(&items, cat, q)
                .iter()
                .map(|i| i.catalog_id.clone())
                .collect::<Vec<_>>()
        };
        assert_eq!(names("POLTRONA", None), vec!["chair"]);
        assert_eq!(names("divisoria", None), vec!["sofa"]);
        assert_eq!(names("  2X1 ", None), vec!["sofa"]);
        assert_eq!(names("", None).len(), 3);
        assert!(names("cama", None).is_empty());
        // Search combines with the category filter.
        assert!(names("poltrona", Some("floor_decoration")).is_empty());
        assert_eq!(names("o", Some("collider")), vec!["chair", "sofa"]);
    }

    #[test]
    fn scrollbar_hidden_when_content_fits() {
        assert_eq!(scrollbar_metrics(400.0, 400.0, 0.0), None);
        assert_eq!(scrollbar_metrics(400.0, 300.0, 0.0), None);
        assert_eq!(scrollbar_metrics(0.0, 300.0, 0.0), None);
    }

    #[test]
    fn scrollbar_thumb_ratio_and_progress() {
        let (ratio, progress) = scrollbar_metrics(200.0, 800.0, 0.0).unwrap();
        assert_eq!((ratio, progress), (0.25, 0.0));
        let (_, mid) = scrollbar_metrics(200.0, 800.0, 300.0).unwrap();
        assert_eq!(mid, 0.5);
        let (_, end) = scrollbar_metrics(200.0, 800.0, 9999.0).unwrap();
        assert_eq!(end, 1.0);
        let (_, start) = scrollbar_metrics(200.0, 800.0, -5.0).unwrap();
        assert_eq!(start, 0.0);
    }

    #[test]
    fn scrollbar_thumb_has_minimum_size() {
        let (ratio, _) = scrollbar_metrics(100.0, 100_000.0, 0.0).unwrap();
        assert_eq!(ratio, 0.1);
    }

    #[test]
    fn normalize_strips_diacritics() {
        assert_eq!(normalize_search("Praça Ônix Ação"), "praca onix acao");
    }

    #[test]
    fn selection_falls_back_to_first_visible() {
        let items = sample();
        let visible = filter_items(&items, Some("collider"), "");
        assert_eq!(
            resolve_selection(&visible, Some("sofa"))
                .unwrap()
                .catalog_id,
            "sofa"
        );
        // "rug" is hidden by the filter.
        assert_eq!(
            resolve_selection(&visible, Some("rug")).unwrap().catalog_id,
            "chair"
        );
        assert_eq!(
            resolve_selection(&visible, None).unwrap().catalog_id,
            "chair"
        );
        assert!(resolve_selection(&[], Some("chair")).is_none());
    }

    #[test]
    fn labels() {
        assert_eq!(category_label("collider"), "Móveis");
        assert_eq!(category_label("custom"), "custom");
        assert_eq!(
            type_label(&item("rug", "floor_decoration")),
            "Piso decorativo"
        );
        assert_eq!(type_label(&item("chair", "collider")), "Móvel sólido");
        assert_eq!(category_icon("floor_decoration"), "ui/icons/rug.png");
        assert_eq!(category_icon("other"), "ui/icons/package.png");
    }
}
