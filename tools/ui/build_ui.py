#!/usr/bin/env python3
"""
build_ui.py
-----------
Gera os templates do bevy_hui a partir de fontes com classes Tailwind.

  assets/ui/src/*.html  (usa class="p-4 bg-slate-900 hover:bg-slate-700")
      -> assets/ui/*.html  (atributos explícitos do bevy_hui)

Rode somente quando alterar um arquivo em assets/ui/src:
  python3 tools/ui/build_ui.py            # gera
  python3 tools/ui/build_ui.py --check    # falha se os gerados estiverem desatualizados
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tailwind  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
UI_DIR = os.path.join(ROOT, "client", "assets", "ui")
SRC_DIR = os.path.join(UI_DIR, "src")
HEADER = "<!-- GENERATED by tools/ui/build_ui.py from assets/ui/src/{name} - do not edit -->\n"

TAG_RE = re.compile(r"<([a-zA-Z_]+)((?:\s+[^<>]*?)?)(/?)>", re.S)
CLASS_RE = re.compile(r'\sclass="([^"]*)"')
ATTR_RE = re.compile(r'([a-zA-Z_:]+)="')


def expand_tag(match, source):
    attrs = match.group(2)
    cls = CLASS_RE.search(attrs)
    if not cls:
        return match.group(0)
    line_start = source.rfind("\n", 0, match.start()) + 1
    indent = re.match(r"\s*", source[line_start:match.start() + 1]).group(0) + "    "
    generated = tailwind.translate(cls.group(1))
    explicit = set(ATTR_RE.findall(CLASS_RE.sub("", attrs)))
    for key, _ in generated:
        if key in explicit:
            raise ValueError(f"attribute {key!r} set both by class and explicitly in <{match.group(1)}>")
    rest = CLASS_RE.sub("", attrs)
    extra = "".join(f'\n{indent}{k}="{v}"' for k, v in generated)
    return f"<{match.group(1)}{rest}{extra}{match.group(3)}>"


def convert(source):
    return TAG_RE.sub(lambda m: expand_tag(m, source), source)


def build(name, source):
    return HEADER.format(name=name) + convert(source)


def main():
    check = "--check" in sys.argv
    stale = []
    for name in sorted(os.listdir(SRC_DIR)):
        if not name.endswith(".html"):
            continue
        with open(os.path.join(SRC_DIR, name), encoding="utf-8") as fh:
            out = build(name, fh.read())
        dst = os.path.join(UI_DIR, name)
        current = open(dst, encoding="utf-8").read() if os.path.exists(dst) else None
        if check:
            if current != out:
                stale.append(name)
        elif current != out:
            with open(dst, "w", encoding="utf-8") as fh:
                fh.write(out)
            print(f"wrote {os.path.relpath(dst, ROOT)}")
    if stale:
        raise SystemExit(f"stale generated templates: {', '.join(stale)} (run tools/ui/build_ui.py)")


if __name__ == "__main__":
    main()
